"""
Verify that when the command executable is itself generated by the build,
and does not exist yet when the implicit command dependencies are scanned,
the action still depends on the generated executable, so it is built first
on a clean build.
"""

import sys

import TestSCons

if sys.platform == 'win32':
    TestSCons.skip_test("Shebang-script executables are not run on Windows.\n")

test = TestSCons.TestSCons()

# The "compiler" is generated by the build from fake-gcc.in.
# It copies its first argument to its second.
test.write('fake-gcc.in', '#!%s\n'
           'import sys\n'
           'with open(sys.argv[2], "w") as f:\n'
           '    f.write(open(sys.argv[1]).read())\n' % TestSCons.python)

test.write('main.c', "main.c contents\n")

test.write('SConstruct', """\
env = Environment(IMPLICIT_COMMAND_DEPENDENCIES=1)
cc = env.Command('tools/mycc', 'fake-gcc.in',
                 [Copy('$TARGET', '$SOURCE'), Chmod('$TARGET', 0o755)])
env.Replace(CC=cc[0].abspath)
env.Command('main.o', 'main.c', '$CC $SOURCE $TARGET')
""")

# No Depends() is needed: the generated compiler is found by the
# implicit command dependency scan and built before main.o.
test.run(arguments='main.o')

test.must_exist('tools/mycc')
test.must_match('main.o', "main.c contents\n")

test.pass_test()

